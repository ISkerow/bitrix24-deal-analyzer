"""Настройки анализа: правила классификации каналов и пороги.

Всё, что зависит от конкретного портала Bitrix24, собрано здесь,
чтобы адаптация под другой портал не требовала правок в логике.
"""

# Каналы, которые считаем WhatsApp. Список правится под конкретный портал:
# коннекторы открытых линий имеют вид WZ<uuid> (Wazzup) или *_WHATSAPP.
# Регистр букв не важен: "WhatsApp" и "WHATSAPP" подходят одинаково.
WHATSAPP_PATTERNS = r"WZ[0-9a-f]{8}|WHATSAPP"

# Точные названия источников, которые тоже считаем WhatsApp. На тестовом
# портале WhatsApp в выгрузке из интерфейса подписан как «Другое».
# ТОЛЬКО для тестовой выгрузки. Для реального клиента
# заменить на его название WhatsApp-линии.
WHATSAPP_SOURCES = {"Другое"}

# SOURCE_ID, которые считаем телефонными обращениями.
# Коды — для выгрузки через API, названия — для CSV из интерфейса.
CALL_SOURCES = {"CALL", "CALLBACK", "Звонок", "Обратный звонок"}

# Код новой воронки: её стадии начинаются с "<код>:", например "C15:NEW".
NEW_PIPELINE = "C15"

# Стадии, на которых заявка считается застрявшей (необработанной).
# Пустой список — найти автоматически: "NEW" и любые "<воронка>:NEW".
# Коды — для выгрузки через API, названия — для CSV из интерфейса.
STUCK_STAGES = ["C15:NEW", "Новая"]

# Стадии, на которых сделка считается выигранной.
# Пустой список — найти автоматически: "WON" и любые "<воронка>:WON".
WON_STAGES = ["WON", "C15:WON", "Сделка успешна"]

# Русские названия колонок из выгрузки интерфейса Битрикс24 -> коды API,
# с которыми работает анализ. Остальные колонки остаются как есть.
# У «Воронки» в API нет текстового кода, поэтому своё имя PIPELINE_NAME.
CSV_COLUMNS = {
    "Воронка": "PIPELINE_NAME",
    "Стадия сделки": "STAGE_ID",
    "Источник": "SOURCE_ID",
    "Дата создания": "DATE_CREATE",
    "Дата изменения": "DATE_MODIFY",
    "Ответственный": "ASSIGNED_BY_ID",
    "Сумма": "OPPORTUNITY",
}

# Часовой пояс клиента: в нём считаются рабочие часы и выходные.
# Время без пояса (CSV из интерфейса) считается временем этого пояса.
CLIENT_TZ = "Asia/Almaty"

# Рабочие часы клиента в формате ЧЧ:ММ. Начало входит, конец — нет:
# 09:00 — рабочее время, 18:00 — уже нет.
WORK_START = "09:00"
WORK_END = "18:00"

# Минимум созданных сделок в месяце, чтобы месяц попал в помесячную
# таблицу (отсекает шум малых выборок).
MIN_MONTH_DEALS = 20

# Куда fetch сохраняет выгрузку и что анализируется по умолчанию.
